function makeOpponentSquad(
  prefix: string,
  names: string[],
  strengthOffset: number
): SquadPlayer[] {
  const roles: SquadPlayer['role'][] = [
    'Batsman',
    'Batsman',
    'Batsman',
    'All-Rounder',
    'Wicketkeeper',
    'All-Rounder',
    'All-Rounder',
    'Bowler',
    'Bowler',
    'Bowler',
    'Bowler',
  ];
  const styles: SquadPlayer['bowlingStyle'][] = [
    'Right-Arm Medium',
    'Off-Spin',
    'Leg-Spin',
    'Right-Arm Fast',
    'Right-Arm Medium',
    'Left-Arm Fast',
    'Off-Spin',
    'Leg-Spin',
    'Left-Arm Fast',
    'Right-Arm Fast',
    'Right-Arm Fast',
  ];
  return names.map((name, idx) => ({
    id: `${prefix}_${idx + 1}`,
    name,
    jerseyNumber: (idx * 7 + 5) % 98 + 1,
    role: roles[idx],
    battingHand: idx % 3 === 1 ? 'Left-Hand' : 'Right-Hand',
    bowlingStyle: styles[idx],
    battingRating: Math.min(95, (idx < 6 ? 82 - idx * 2 : 52 - idx * 2) + strengthOffset),
    bowlingRating: Math.min(95, (idx >= 6 ? 86 : 55) + strengthOffset),
    fieldingRating: Math.min(92, 78 + strengthOffset),
    isCaptain: idx === 2,
    isViceCaptain: idx === 9,
  }));
}

